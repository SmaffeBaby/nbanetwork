  SELECT user_id,'prediction',p_game_id,100,p_details FROM public.game_predictions WHERE game_id=p_game_id AND side=p_winner_side AND updated_at<p_starts_at
  ON CONFLICT(user_id,kind,game_id) DO NOTHING;
 END IF;
END $$;
